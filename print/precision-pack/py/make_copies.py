"""Copy the Precision Teaching sheet code into this folder, unchanged, for the print page (runs in the browser).

    python3 print/precision-pack/py/make_copies.py

data.py and cloze_bank.py (+ cloze_more.json) are copied whole. pt_render.py is the sheet-drawing part of
precision-teaching/app.py (renderer, build_week_pdf, _KIND, _targets_to_sheets) copied line for line, with a
short header that stands in for Streamlit (only st.session_state is used) and name_stamps (names are drawn
straight onto the sheets here, so no stamping is needed). Re-run it after changing the old sheet code.
"""
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent.parent.parent / "precision-teaching"

for fn in ("data.py", "cloze_bank.py", "cloze_more.json"):
    shutil.copyfile(SRC / fn, HERE / fn)

app = (SRC / "app.py").read_text(encoding="utf-8").splitlines()


def block(start_pat, end_pat):
    """Lines from the first line matching start_pat up to (not including) the first later line matching end_pat."""
    i = next(n for n, l in enumerate(app) if re.match(start_pat, l))
    j = next(n for n in range(i + 1, len(app)) if re.match(end_pat, app[n]))
    return app[i:j]


HEADER = '''"""GENERATED by make_copies.py from precision-teaching/app.py. Do not edit: edit app.py and re-run."""
import json
import os
from datetime import date
from reportlab.lib.units import mm as _mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
import name_stamps


class _St:                      # stands in for streamlit: the sheet code only reads st.session_state
    session_state = {}


st = _St()
'''
parts = [
    block(r"^# Sassoon Infant is the house font", r"^from data import"),
    block(r"^from data import", r"^$"),
    block(r"^# ── PDF Renderer", r"^# ── Year Group Filter"),
    block(r"^_KIND = ", r"^$"),
    block(r"^def _targets_to_sheets", r"^# The print screen is reached"),
]
out = HEADER + "\n" + "\n\n".join("\n".join(p).rstrip() + "\n" for p in parts)
(HERE / "pt_render.py").write_text(out, encoding="utf-8")

(HERE / "name_stamps.py").write_text(
    '"""Stand-in for precision-teaching/name_stamps.py: this page draws the names itself, so nothing is logged."""\n'
    "def begin():\n    pass\n\n\ndef log(*a, **k):\n    pass\n\n\ndef finish(pdf_bytes):\n    return pdf_bytes\n",
    encoding="utf-8")
print("copied into", HERE)
